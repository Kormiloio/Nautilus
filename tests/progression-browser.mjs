import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const output = '/private/tmp/nautilus-progression-browser';
mkdirSync(output, { recursive: true });
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:3102/sentence-preview.html');
    await page.locator('#family-play-title').waitFor();
    assert.equal(await page.locator('#family-play-title').innerText(), 'Familiar words first');
    await page.locator('[aria-label="Sentence activity"]').selectOption({ label: 'One sentence pattern' });
    const pattern = page.locator('[data-pattern-lesson]');
    assert.equal(await pattern.locator('h2').innerText(), 'See the sentence');
    assert.equal(await page.locator('#family-play-next').isDisabled(), true);
    await pattern.locator('[data-pattern-next]').click();
    assert.equal(await pattern.locator('.pattern-parts > div').count(), 3);
    await page.locator('[aria-label="Sentence activity"]').selectOption({ label: 'One sentence pattern' });
    assert.equal(await pattern.locator('h2').innerText(), 'Take it apart');
    await page.screenshot({ path: `${output}/pattern-${width}.png`, fullPage: true });
    await pattern.locator('[data-pattern-next]').click();
    assert.equal(await pattern.locator('[data-pattern-next]').isDisabled(), true);
    await pattern.locator('[data-pattern-answer="This is"]').click();
    assert.ok((await pattern.locator('.pattern-feedback').innerText()).includes('Try another'));
    await pattern.locator('[data-pattern-answer="That is not"]').click();
    assert.equal(await pattern.locator('[data-pattern-next]').isEnabled(), true);
    await pattern.locator('[data-pattern-next]').click();
    await pattern.locator('[data-pattern-next]').click();
    assert.equal(await pattern.locator('h2').innerText(), 'See the sentence');
    assert.ok((await pattern.locator('.pattern-meta').innerText()).includes('Pattern 2 of 2'));
    await pattern.locator('[data-pattern-back]').click();
    assert.ok((await pattern.locator('.pattern-meta').innerText()).includes('Pattern 1 of 2'));
    await pattern.locator('[data-pattern-next]').click();
    await pattern.locator('[data-pattern-next]').click();
    await pattern.locator('[data-pattern-next]').click();
    await pattern.locator('[data-pattern-answer="Here is"]').click();
    await pattern.locator('[data-pattern-next]').click();
    assert.equal(await page.locator('#family-play-next').isEnabled(), true);
    await page.locator('[aria-label="Sentence activity"]').selectOption({ label: 'One sentence pattern' });
    assert.equal(await page.locator('#family-play-next').isEnabled(), true);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `${output}/pattern-ready-${width}.png`, fullPage: true });
    await page.locator('[aria-label="Sentence activity"]').selectOption({ label: 'Build the sentence' });
    assert.equal(await page.locator('[data-sentence-answer]').count(), 1);
    await page.screenshot({ path: `${output}/sentence-${width}.png`, fullPage: true });
    await page.goto('http://127.0.0.1:3102/listening-preview.html');
    await page.locator('[data-study-start]').waitFor();
    assert.equal(await page.locator('h1').innerText(), 'Read and hear first');
    assert.ok((await page.locator('.listening-study').innerText()).includes(' = '));
    assert.equal(await page.locator('[data-listening-check]').count(), 0);
    await page.screenshot({ path: `${output}/listening-preparation-${width}.png`, fullPage: true });
    await page.route('**/__detective_test', route => route.fulfill({ contentType: 'text/html', body: '<html><head><link rel="stylesheet" href="/css/style.css"></head><body><div id="app"></div></body></html>' }));
    await page.goto('http://127.0.0.1:3102/__detective_test');
    await page.evaluate(async () => {
      const { getSideQuestForProgress } = await import('/content/side-quests.js');
      const { renderSideQuestView } = await import('/components/side-quest-view.js');
      const quest = getSideQuestForProgress('montenegrin-en', 40);
      const state = { sideQuest: quest, familySideQuestState: { currentCase: 0, status: 'active', cases: quest.cases, allLocked: false, lockedCount: 0, participantCount: 2, people: [], isController: true } };
      const actions = new Proxy({}, { get: () => () => {} });
      renderSideQuestView(document.getElementById('app'), state, actions);
    });
    assert.ok((await page.locator('.detective-case').innerText()).includes('Ovaj grad ima veliki trg.'));
    assert.ok((await page.locator('#side-quest-title').innerText()).includes('Case pack 2'));
    assert.ok((await page.locator('.detective-clue-words').innerText()).includes(' = '));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `${output}/detective-${width}.png`, fullPage: true });
    assert.deepEqual(errors, []);
    await page.close();
  }
  console.log('PASS: desktop/mobile vocabulary preparation, frame explanation, listening pre-teaching, and fresh Detective edition render without errors. Screenshots: ' + output);
} finally { await browser.close(); }
